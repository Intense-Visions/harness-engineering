#!/usr/bin/env node
// Generate src/rules/index.ts — the rule barrel — from the rule files in
// src/rules/. A rule file's basename IS its rule name; its default export IS the
// rule. So registration is fully derivable: drop a `my-rule.ts` in src/rules/ and
// it is picked up automatically — NO hand-edit of the barrel required.
//
// Why this exists: hand-editing a growing barrel (import + object entry, in the
// right place, no dupes) is a precise multi-site edit that weak/local coding
// models reliably get wrong (missing import, duplicate key, entry after the
// closing brace). Deriving it removes that failure mode entirely.
//
// Output is deterministic (sorted) and prettier-shaped, so regenerating when no
// rule files changed is a no-op (no diff). Run via `pnpm generate:rules`; also
// wired into prebuild/pretest/pretypecheck so the barrel is always fresh.
//
// `--check` exits non-zero if the committed barrel is stale (for CI), without
// writing.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const rulesDir = join(here, '..', 'src', 'rules');
const outFile = join(rulesDir, 'index.ts');

/** kebab-case rule name → camelCase import binding. */
const toBinding = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const ruleNames = readdirSync(rulesDir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts' && !f.endsWith('.test.ts'))
  .map((f) => f.slice(0, -3))
  .sort();

const imports = ruleNames.map((n) => `import ${toBinding(n)} from './${n}';`).join('\n');
const entries = ruleNames.map((n) => `  '${n}': ${toBinding(n)},`).join('\n');

const content = `// src/rules/index.ts
//
// AUTO-GENERATED by scripts/generate-rules-barrel.mjs — DO NOT EDIT BY HAND.
// Add a rule file to src/rules/ and it is registered automatically; run
// \`pnpm generate:rules\` (or any build/test) to refresh this file.
${imports}
import type { TSESLint } from '@typescript-eslint/utils';

// Explicit annotation so the exported type is nameable via the direct
// @typescript-eslint/utils dependency rather than the hoisted .pnpm path
// (avoids TS2742 in downstream DTS builds).
export const rules: Record<string, TSESLint.RuleModule<string, unknown[]>> = {
${entries}
};
`;

if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(outFile, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== content) {
    console.error(
      `[generate-rules-barrel] ${outFile} is STALE — run \`pnpm generate:rules\` and commit.`
    );
    process.exit(1);
  }
  console.log(`[generate-rules-barrel] barrel is fresh (${ruleNames.length} rules).`);
} else {
  writeFileSync(outFile, content);
  console.log(`[generate-rules-barrel] wrote ${ruleNames.length} rules to ${outFile}.`);
}
